# --- VALIDATION FUNCTIONS ---
def get_valid_prev_gpa():
    while True:
        try:
            prev_gpa = float(input("Cumulative GPA (CGPA) (0.00 - 4.00): "))
            if 0.00 <= prev_gpa <= 4.00:
                return prev_gpa
            print("[Error] CGPA must be between 0.00 and 4.00.")
        except ValueError:
            print("[Error] Please enter a valid number.")

def get_valid_attendance():
    while True:
        try:
            att = float(input("\nAverage Attendance Percentage (0 - 100): "))
            if 0 <= att <= 100:
                if att < 80:
                    print("  ⚠️ [Warning] You need at least 80% attendance to be eligible for exams!")
                return att
            print("[Error] Attendance must be between 0 and 100%.")
        except ValueError:
            print("[Error] Please enter a valid number.")

def get_valid_study_hours(num_modules):
    # Assuming 1 module = 3 credits roughly (adjust if your university uses different standard)
    credits = num_modules * 3
    min_hours = (credits * 50) / 15
    print(f"\n  📘 Based on BIT By-Laws ({credits} credits), your minimum required study time is {min_hours:.1f} hours/week.")

    while True:
        try:
            study = float(input(f"Study Hours Per Week (Must be >= {min_hours:.1f}): "))
            if min_hours <= study <= 168:
                return study
            elif study < min_hours:
                print(f"[Error] According to BIT By-Laws, you must study at least {min_hours:.1f} hours.")
            else:
                print("[Error] There are only 168 hours in a week!")
        except ValueError:
            print("[Error] Please enter a valid number.")

def get_valid_sleep():
    while True:
        try:
            sleep = float(input("\nSleep Hours Per Day (0 - 24): "))
            if 0 <= sleep <= 24:
                if sleep < 7 or sleep > 9:
                    print("  ⚠️ [NSF Warning] The National Sleep Foundation recommends 7 to 9 hours for adults (18-64).")
                    print("  ⚠️ Deviating from this standard mathematically lowers your cognitive performance and predicted GPA in our ML Model.")
                else:
                    print("  ✅ Excellent! You are within the NSF recommended 7-9 hours of healthy sleep.")
                return sleep
            print("[Error] Sleep must be between 0 and 24 hours.")
        except ValueError:
            print("[Error] Please enter a valid number.")

def get_valid_stress():
    while True:
        try:
            stress = float(input("Stress Level (1.0 to 5.0): "))
            if 1.0 <= stress <= 5.0:
                return stress
            print("[Error] Stress level must be between 1.0 and 5.0.")
        except ValueError:
            print("[Error] Please enter a valid number.")

