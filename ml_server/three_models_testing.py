import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

# ==========================================
# 1. LOAD THE DATASET
# ==========================================
df = pd.read_csv("future_gpa_dataset_final.csv").dropna()
y_target = df['Future_GPA']

# ==========================================
# 2. FEATURE SELECTION (TRI-MODEL SUITE)
# ==========================================
features_model_a = [
    'Previous_GPA', 'Attendance_Percentage',
    'Study_Hours_Per_Week', 'Sleep_Hours_Per_Day', 'Stress_Level'
]

features_model_b = [
    'Mid_Mark', 'Assignment_Mark', 'Attendance_Percentage',
    'Study_Hours_Per_Week', 'Sleep_Hours_Per_Day', 'Stress_Level'
]

# The Master Model: Combines History + Current Academic Performance + Lifestyle
features_model_c = [
    'Previous_GPA', 'Mid_Mark', 'Assignment_Mark', 'Attendance_Percentage',
    'Study_Hours_Per_Week', 'Sleep_Hours_Per_Day', 'Stress_Level'
]

X_model_a = df[features_model_a]
X_model_b = df[features_model_b]
X_model_c = df[features_model_c]

# Split Data (80% Train, 20% Test)
Xa_train, Xa_test, ya_train, ya_test = train_test_split(X_model_a, y_target, test_size=0.2, random_state=42)
Xb_train, Xb_test, yb_train, yb_test = train_test_split(X_model_b, y_target, test_size=0.2, random_state=42)
Xc_train, Xc_test, yc_train, yc_test = train_test_split(X_model_c, y_target, test_size=0.2, random_state=42)

# ==========================================
# 3. TRAIN ALL THREE MODELS
# ==========================================
model_a = LinearRegression().fit(Xa_train, ya_train)
model_b = LinearRegression().fit(Xb_train, yb_train)
model_c = LinearRegression().fit(Xc_train, yc_train)

# Predictions (Clipped to 0.0 - 4.0 max GPA)
pred_a = np.clip(model_a.predict(Xa_test), 0.0, 4.0)
pred_b = np.clip(model_b.predict(Xb_test), 0.0, 4.0)
pred_c = np.clip(model_c.predict(Xc_test), 0.0, 4.0)

# ==========================================
# 4. ADVANCED EVALUATION METRICS
# ==========================================
print("======================================================")
print(" 🎓 TRI-MODEL ML EVALUATION (LIFECYCLE SUITE)")
