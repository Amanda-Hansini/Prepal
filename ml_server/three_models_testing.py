def evaluate_and_print(name, desc, y_test, preds, X_test):
    r2 = r2_score(y_test, preds)
    mae = mean_absolute_error(y_test, preds)
    mse = mean_squared_error(y_test, preds)
    rmse = np.sqrt(mse)

    n = len(y_test)
    p = X_test.shape[1]
    adj_r2 = 1 - (1 - r2) * (n - 1) / (n - p - 1)

    print(f"\n--- {name}: {desc} ---")
    print(f"1. R-Squared (R²):         {r2*100:.2f}%")
    print(f"2. Adjusted R-Squared:     {adj_r2*100:.2f}%")
    print(f"3. Mean Absolute Error:    {mae:.4f} GPA Points")
    print(f"4. Mean Squared Error:     {mse:.4f}")
    print(f"5. Root Mean Sq Error:     {rmse:.4f} GPA Points")

evaluate_and_print("MODEL A", "Pre-Semester Baseline (Returning Students)", ya_test, pred_a, Xa_test)
evaluate_and_print("MODEL B", "Mid-Semester Performance (New Students)", yb_test, pred_b, Xb_test)
evaluate_and_print("MODEL C", "Comprehensive Master Model (Returning Mid-Semester)", yc_test, pred_c, Xc_test)

